# Lists

marks = [95,96,90,98]

print(marks)      # [95,96,90,98]

print(marks[0])   # 95

print(marks[0:2]) # [95,96]


# append()

marks.append(100)

print(marks)


# insert()

marks.insert(0,99)

print(marks)


# sort()

marks.sort()

print(marks)


# reverse()

marks.reverse()

print(marks)


# loops

for i in marks:
    print(i)